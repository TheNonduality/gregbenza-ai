// ---------------------------------------------------------------------------
// Emits dist/_redirects after the Astro build.
//
// WHY THIS EXISTS: agents reliably guess /projects/<slug>.md for a post's
// machine-readable twin; the real file is /projects/<slug>/<slug>.md. The
// obvious netlify.toml rule — from "/projects/:slug.md" to
// "/projects/:slug/:slug.md" — does NOT work: Netlify substitutes a
// placeholder only once, so the target ships as "/projects/:slug/explorer-fix.md"
// with the first :slug left literal. Verified against a real deploy, not
// assumed. So the rules are written out explicitly instead.
//
// The list is derived from the BUILT OUTPUT, not from a hand-kept list, so
// every future post is covered the moment it builds — nothing to remember.
// ---------------------------------------------------------------------------

import { readdir, writeFile, access } from 'node:fs/promises';
import path from 'node:path';

const PROJECTS = path.join('dist', 'projects');

const rules = [];
let entries = [];
try {
  entries = await readdir(PROJECTS, { withFileTypes: true });
} catch {
  // No projects built yet — nothing to redirect.
}

for (const entry of entries) {
  if (!entry.isDirectory()) continue;
  const slug = entry.name;
  const twin = path.join(PROJECTS, slug, `${slug}.md`);
  try {
    await access(twin);
  } catch {
    continue; // This post has no markdown twin; nothing to point at.
  }
  // 301! — the bang forces the rule even though a file could exist at the
  // source path, so behaviour can't drift if one ever does.
  rules.push(`/projects/${slug}.md  /projects/${slug}/${slug}.md  301!`);
}

const body = [
  '# Generated by scripts/emit-redirects.mjs — do not edit by hand.',
  '# Parked 2026-09-07: /waystation is not published while it is worked on. 410 tells an index it is gone,',
  '# which is honest and reversible — delete these three lines when it comes back.',
  '/waystation/*  /  410!',
  '/api/waystation/*  /  410!',
  '/mcp/waystation  /  410!',
  '/mcp/waystation/*  /  410!',
  '/projects/*  /  410!',
  '# Agents guess /projects/<slug>.md; the real twin lives one level deeper.',
  ...rules,
  '',
].join('\n');

await writeFile(path.join('dist', '_redirects'), body, 'utf8');
console.log(`[redirects] wrote ${rules.length} rule(s) to dist/_redirects`);
